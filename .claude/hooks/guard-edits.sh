#!/usr/bin/env bash
# PreToolUse guard for Edit, Write and NotebookEdit.
#
#   exit 2 + stderr        refuse; Claude reads stderr as the reason
#   JSON "ask" on stdout   the user decides, with the reason in the prompt
#   JSON additionalContext allow, and tell Claude something it must weigh
#   exit 0, no output      allow
#
# A habit guard on the Edit/Write path, not a security boundary: a shell
# command goes around it. It exists for the mistakes that are cheap to catch
# at write time and expensive to discover later. Rules needing real parsing
# belong in the test suite, where they can be debugged.

set -uo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source-path=SCRIPTDIR source=lib.sh
. "$here/lib.sh"

payload="$(cat)"
path="$(json_field "$payload" file_path)"
[ -n "$path" ] || path="$(json_field "$payload" notebook_path)"
[ -n "$path" ] || exit 0
rel="$(project_relative "$path")"
base="${rel##*/}"

refuse() {
  printf 'BLOCKED: %s\n' "$@" >&2
  exit 2
}

ask() {
  printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"ask","permissionDecisionReason":%s}}\n' \
    "$(json_string "$1")"
  exit 0
}

note() {
  printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","additionalContext":%s}}\n' \
    "$(json_string "$1")"
  exit 0
}

# The text being written, without the text being replaced: removing a bad
# import must not be refused for containing it.
new_text() {
  printf '%s' "$payload" | sed -E 's/"old_string"[[:space:]]*:[[:space:]]*"([^"\\]|\\.)*"//g'
}

# 1. Secrets are edited by a human only.
case "$base" in
  .env.example | .env.sample | .env.template) ;;
  .env | .env.* | *.pem | *.key | id_rsa | id_ed25519)
    refuse "$rel holds credentials. Edit it yourself and say what changed -- an agent never writes secrets." ;;
esac

# 2. Evaluation ground truth is a human decision. The failure mode of eval-driven
#    work is "the eval failed, so adjust the expected answer": the bar drops and
#    the suite stays green. Globs come from sdd.toml [guards] ground_truth.
truth="$(toml_array "$(project_dir)/sdd.toml" guards ground_truth)"
[ -n "$truth" ] || truth="tests/evals/golden/*"
while IFS= read -r glob; do
  [ -n "$glob" ] || continue
  # shellcheck disable=SC2254  # the glob is meant to match
  case "$rel" in
    $glob) refuse "$rel is evaluation ground truth, written by a human. Propose the cases; let the user write them." ;;
  esac
done <<EOF
$truth
EOF

# 3. Generated files are regenerated by the tool that owns them.
case "$base" in
  uv.lock | poetry.lock | Pipfile.lock | package-lock.json | pnpm-lock.yaml | yarn.lock | Cargo.lock | go.sum)
    refuse "$rel is generated. Change the manifest and regenerate it with its tool (uv sync, npm install, ...)." ;;
esac

# 4. CI is where enforcement is decided; an agent that could rewrite it could
#    quietly stop enforcing anything. Propose it in docs/ci/, a person moves it.
case "$rel" in
  .github/workflows/*)
    refuse "$rel is CI. Propose the change under docs/ci/ and let a person move it into place." ;;
esac

# 5. The decision layer imports nothing but the standard library (python pack).
#    The architecture test enforces the full allowlist; this catches the common
#    SDKs at write time and says why.
case "$rel" in
  src/*/domain/*.py)
    if new_text | grep -Eq '(import|from)[[:space:]]+(langchain[a-z0-9_]*|langgraph[a-z0-9_]*|langsmith|deepagents|llama_index|openai|anthropic|google|mlflow|langfuse|litellm|pinecone|chromadb|qdrant_client|weaviate|psycopg[0-9]*|sqlalchemy|boto3|requests|httpx|aiohttp|pydantic|dotenv)([^a-z0-9_]|$)'; then
      refuse "domain/ imports the standard library only -- no SDK, client or framework. Put the call in infrastructure/ and pass its result in as data."
    fi ;;
esac

# 6. The living spec is written by `openspec archive`, never by hand. A change
#    writes a delta under openspec/changes/<id>/specs/ instead.
case "$rel" in
  openspec/specs/*)
    ask "$rel is the living spec: archive writes it. Amend a requirement with a delta in openspec/changes/<id>/specs/. Approve only a Purpose-only fix." ;;
esac

# 7. The enforcement itself. An agent weakening its own checks needs a human
#    to agree, every time.
case "$rel" in
  .claude/settings.json | .claude/hooks/* | .claude/sdd/sdd.sh | .claude/sdd/sdd.py | .claude/sdd/sddlib/* | .claude/sdd/tests/* | .claude/sdd/fixtures/* | openspec/schemas/* | scripts/check.sh)
    ask "$rel is part of the method's enforcement. Changing it changes what gets checked -- approve only if you meant to." ;;
esac

# 8. A prompt is behaviour no deterministic test asserts (python pack).
case "$rel" in
  src/*/application/*.py)
    if new_text | grep -Eq '[A-Z_]*(PROMPT|TEMPLATE|INSTRUCTIONS)[A-Z_]*[[:space:]]*(:[^=]*)?='; then
      note "$rel holds prompt text. A prompt is behaviour that no deterministic test asserts: if its text changed, its version moves, and the evaluated requirements that depend on it need /eval before this change lands."
    fi ;;
esac

exit 0
